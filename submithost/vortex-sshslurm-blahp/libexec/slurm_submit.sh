#!/bin/bash
#
# slurm_submit.sh -- "Slurm over plain ssh/scp" blahp submit script.
#
# Installed in a PRIVATE blahp libexec dir (see install.sh), so the stock
# /usr/libexec/blahp/slurm_submit.sh is untouched. blahpd runs locally on the
# submit host; this script:
#   1. builds an sbatch script (same #SBATCH mapping as the stock script,
#      incl. <lrms>_local_submit_attributes.sh used by Pegasus profiles),
#   2. creates <remote_base>/<bl_XXXXXX>/ on the cluster over ssh,
#   3. scp's the executable (unless transfer_executable=false), stdin and
#      transfer_input_files into it,
#   4. runs sbatch over ssh and records where stdout/stderr/outputs live, so
#      slurm_status.sh can scp them back when the job finishes.
#
# Modeled on Pegasus 5.1.3's sfapi_submit.sh (share/pegasus/htcondor/glite),
# which uses the same "local blahp, plugin moves the files" design.

. `dirname $0`/blah_common_submit_functions.sh
. `dirname $0`/sshslurm_common.sh

bls_submit_args_prefix="#SBATCH"

# Pegasus (glite/ssh styles) puts _CONDOR_TRANSFER_EXECUTABLE=<true|false>
# into the job environment; blahp has no other way to learn it.
bls_transfer_executable_env_regex="^_CONDOR_TRANSFER_EXECUTABLE=false$"

sshslurm_job_env() {
    if [ "x$bls_opt_environment" != "x" ] ; then
        echo ""
        echo "# Job environment"
        eval "env_array=($bls_opt_environment)"
        for env_var in "${env_array[@]}"; do
            echo export \"$env_var\"
            if [[ $env_var =~ $bls_transfer_executable_env_regex ]] ; then
                bls_opt_stgcmd="no"
            fi
        done
    elif [ "x$bls_opt_envir" != "x" ] ; then
        echo ""
        echo "# Job environment (old format)"
        echo "`echo ';'$bls_opt_envir | sed -e 's/;[^=]*;/;/g' -e 's/;[^=]*$//g' | sed -e 's/;\([^=]*\)=\([^;]*\)/;export \1=\"\2\"/g' | awk 'BEGIN { RS = ";" } ; { print $0 }'`"
    fi
}

fail() {
    rm -f "$bls_tmp_file"
    echo "Error: $*" >&2
    exit 1
}

bls_parse_submit_options "$@"

# Only temp files: stdin/stdout/stderr live on the cluster, not in a local
# blahp sandbox (bls_setup_all_files would assume a shared filesystem).
bls_setup_temp_files


remote_base=$(sshslurm_remote_base_abs) || fail "cannot determine remote base dir on $sshslurm_host"
remote_dir="$remote_base/$bls_tmp_name"
remote_stdout="$remote_dir/$bls_tmp_name.out"
remote_stderr="$remote_dir/$bls_tmp_name.err"

###############################################################
# sbatch script
###############################################################
# https://man.archlinux.org/man/sbatch.1.en
cat > $bls_tmp_file << end_of_preamble
#!/bin/bash -l
# SLURM job generated by `basename $0` (ssh/scp blahp) on `/bin/date`
#SBATCH --chdir $remote_dir
#SBATCH --output $remote_stdout
#SBATCH --error $remote_stderr
end_of_preamble

#if [ "x$bls_opt_project" != "x" ] ; then
    #echo "#SBATCH -A $bls_opt_project" >> $bls_tmp_file
#fi
if [ "x$bls_opt_runtime" != "x" ] ; then
    #echo "#SBATCH -t $((bls_opt_runtime / 60))" >> $bls_tmp_file
    echo "#SBATCH --time 00:10:00" >> $bls_tmp_file
fi
if [ "x$bls_opt_req_mem" != "x" ] ; then
    echo "#SBATCH --mem=${bls_opt_req_mem}" >> $bls_tmp_file
fi

#cluster_name=`echo "$bls_opt_queue" | cut -s -f2 -d@`
#if [ "$cluster_name" != "" ] ; then
    #bls_opt_queue=`echo "$bls_opt_queue" | cut -f1 -d@`
#fi
#[ -z "$bls_opt_queue" ] || grep -q "^#SBATCH -p" $bls_tmp_file || echo "#SBATCH -p $bls_opt_queue" >> $bls_tmp_file
#[ -z "$cluster_name" ] || grep -q "^#SBATCH -M" $bls_tmp_file || echo "#SBATCH -M $cluster_name" >> $bls_tmp_file

# MPI / whole-node attributes (same as stock slurm_submit.sh)
#if [ "x$bls_opt_wholenodes" == "xyes" ] ; then
    #bls_opt_hostsmpsize=${bls_opt_hostsmpsize:-1}
    #if [[ ! -z "$bls_opt_smpgranularity" ]] ; then
        #echo "#SBATCH -N ${bls_opt_hostnumber:-1}" >> $bls_tmp_file
        #echo "#SBATCH --ntasks-per-node $bls_opt_smpgranularity" >> $bls_tmp_file
        #echo "#SBATCH --exclusive" >> $bls_tmp_file
    #elif [[ ! -z "$bls_opt_hostnumber" ]] ; then
        #echo "#SBATCH -N $bls_opt_hostnumber" >> $bls_tmp_file
        #[[ $bls_opt_mpinodes -gt 0 ]] && echo "#SBATCH -n $bls_opt_mpinodes" >> $bls_tmp_file
        #echo "#SBATCH --exclusive" >> $bls_tmp_file
    #fi
#else
    #[[ ! -z "$bls_opt_mpinodes" ]] && echo "#SBATCH -n $bls_opt_mpinodes" >> $bls_tmp_file
    #if [[ ! -z "$bls_opt_smpgranularity" ]] ; then
        #echo "#SBATCH --ntasks-per-node $bls_opt_smpgranularity" >> $bls_tmp_file
    #elif [[ ! -z "$bls_opt_hostnumber" ]] ; then
        #echo "#SBATCH -N $bls_opt_hostnumber" >> $bls_tmp_file
    #fi
#fi

echo "#SBATCH --nodes=1-1" >> $bls_tmp_file
echo "#SBATCH --ntasks-per-node=1" >> $bls_tmp_file

# GPUs
#[ -z "$bls_opt_gpunumber" ] || [ -z "$bls_opt_gpumodel" ] || echo "#SBATCH --gres=gpu:${bls_opt_gpumodel}:${bls_opt_gpunumber}" >> $bls_tmp_file
#[ -z "$bls_opt_gpunumber" ] || [ ! -z "$bls_opt_gpumodel" ] || echo "#SBATCH --gres=gpu:${bls_opt_gpunumber}" >> $bls_tmp_file

echo "#SBATCH --cluster=ub-hpc" >> $bls_tmp_file
echo "#SBATCH --partition=general-compute" >> $bls_tmp_file
echo "#SBATCH --qos=general-compute" >> $bls_tmp_file

# slurm_local_submit_attributes.sh (Pegasus maps cores/memory/runtime/
# project/glite.arguments here) and +remote_cerequirements / extra args.
# Must come after the other #SBATCH lines and before any command.
bls_set_up_local_and_extra_args

sshslurm_job_env >> $bls_tmp_file

###############################################################
# Job body + list of files to upload
###############################################################
upload_files=()
run_cmd=${bls_opt_the_command}
if [ "x${bls_opt_stgcmd}" == "xyes" ] ; then
    exe_local=$(sshslurm_local_path "$bls_opt_the_command")
    [ -f "$exe_local" ] || fail "executable not found locally: $exe_local"
    upload_files+=("$exe_local")
    run_cmd="./$(basename "$bls_opt_the_command")"
fi

if [[ -n "$bls_opt_stdin" && "$bls_opt_stdin" != "/dev/null" ]] ; then
    stdin_local=$(sshslurm_local_path "$bls_opt_stdin")
    if [ -f "$stdin_local" ]; then
        upload_files+=("$stdin_local")
        run_cmd="${run_cmd} < \"./$(basename "$stdin_local")\""
    fi
fi

if [ -n "$bls_opt_inputflstring" ] && [ -r "$bls_opt_inputflstring" ] ; then
    while read -r f; do
        [ -z "$f" ] && continue
        case "$f" in *://*) echo "Warning: skipping URL input $f" >&2; continue;; esac
        upload_files+=("$(sshslurm_local_path "$f")")
    done < "$bls_opt_inputflstring"
fi

{
    echo ""
    echo "cd \"$remote_dir\" || exit 1"
    [ "x${bls_opt_stgcmd}" == "xyes" ] && echo "chmod u+x \"$(basename "$bls_opt_the_command")\""
    echo "${run_cmd} ${bls_arguments}"
    echo 'rc=$?'
    echo 'echo $rc > .blahp_exitcode'
    echo 'exit $rc'
} >> $bls_tmp_file

bls_save_submit     # creates $blah_debug_save_submit_info/<name>.debug if enabled
if [ -d "$blah_debug_save_submit_info" ] && [ -n "$bls_tmp_name" ]; then
    bls_info_dir="$blah_debug_save_submit_info/$bls_tmp_name.debug"
    mkdir -p "$bls_info_dir" && cp "$bls_tmp_file" "$bls_info_dir/submit.sbatch"
fi

###############################################################
# Upload + sbatch
###############################################################
rssh "mkdir -p '$remote_dir'" || fail "ssh mkdir $remote_dir on $sshslurm_host failed"
cp "$bls_tmp_file" "$bls_tmp_file.sbatch"
rscp_up "$remote_dir" "${upload_files[@]}" "$bls_tmp_file.sbatch" \
    || { rm -f "$bls_tmp_file.sbatch"; fail "scp of input files to $sshslurm_host:$remote_dir failed"; }
rm -f "$bls_tmp_file.sbatch"

sbatch_out=$(rbash "$remote_dir" "$bls_tmp_name.sbatch" 2>&1 <<'EOF'
cd "$1" && sbatch --parsable "$2"
EOF
)
retcode=$?
jobID=$(echo "$sbatch_out" | grep -E '^[0-9]+(;.*)?$' | tail -1 | cut -d';' -f1)
if [ "$retcode" != "0" ] || [ -z "$jobID" ] ; then
    fail "sbatch on $sshslurm_host failed: $sbatch_out"
fi

datenow=`date +%Y%m%d`
blahp_jobID="slurm/$datenow/$jobID"
[ -n "$cluster_name" ] && blahp_jobID="${blahp_jobID}@${cluster_name}"
state_file=$(sshslurm_state_file "$blahp_jobID")

# where to put things when the job is done
{
    echo "remote_dir::$remote_dir"
    if [ -n "$bls_opt_stdout" ] && [ "$bls_opt_stdout" != "/dev/null" ]; then
        echo "stdout::$(sshslurm_local_path "$bls_opt_stdout"):$remote_stdout"
    fi
    if [ -n "$bls_opt_stderr" ] && [ "$bls_opt_stderr" != "/dev/null" ]; then
        if [ "$bls_opt_stderr" == "$bls_opt_stdout" ]; then
            echo "append::$(sshslurm_local_path "$bls_opt_stderr"):$remote_stderr"
        else
            echo "stderr::$(sshslurm_local_path "$bls_opt_stderr"):$remote_stderr"
        fi
    fi
    if [ -n "$bls_opt_outputflstring" ] && [ -r "$bls_opt_outputflstring" ]; then
        # -R file (if any) is line-parallel to the -O file: same line = remap
        remapfile=/dev/null
        [ -n "$bls_opt_outputflstringremap" ] && [ -r "$bls_opt_outputflstringremap" ] \
            && remapfile=$bls_opt_outputflstringremap
        while read -r f <&5; do
            r=""; read -r r <&6
            [ -z "$f" ] && continue
            dest=${r:-$f}
            echo "output::$(sshslurm_local_path "$dest"):$remote_dir/$(basename "$f")"
        done 5< "$bls_opt_outputflstring" 6< "$remapfile"
    fi
} > "$state_file"

[ -d "$bls_info_dir" ] && cp "$state_file" "$bls_info_dir/"

echo "BLAHP_JOBID_PREFIX$blahp_jobID"
bls_wrap_up_submit
exit 0
